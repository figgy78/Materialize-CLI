#!/usr/bin/env python3
"""Local web UI for Materialize CLI.

Serves a page on 127.0.0.1 that drives the installed `materialize` binary:
upload a diffuse texture, run the real CLI, preview the six PBR maps it
writes (2D grid + lit 3D material preview), download them as a zip.

Standard library only. Usage:  python3 ui/serve.py [--port N] [--no-open]
"""

import argparse
import io
import json
import os
import shutil
import subprocess
import sys
import tempfile
import time
import uuid
import webbrowser
import zipfile
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from urllib.parse import urlparse, parse_qs, unquote

MAPS = ["height", "normal", "metallic", "smoothness", "edge", "ao",
        "maskmap", "detail"]
# Channel-packed RGBA maps; their alpha carries data, so JPEG cannot hold them.
PACKED = {"maskmap", "detail"}
# How the Unity export folder names each file, and which map feeds it.
UNITY_FILES = [
    ("Albedo", None), ("Normal", "normal"), ("MaskMap", "maskmap"),
    ("Detail", "detail"), ("Height", "height"),
]
UI_DIR = Path(__file__).parent.resolve()
REPO_DIR = UI_DIR.parent

# Exit codes documented in README.md, surfaced as readable messages.
EXIT_MEANING = {
    1: "Generic error",
    2: "Input file not found",
    3: "Unsupported input format",
    4: "GPU error (no adapter available)",
    5: "I/O error (permissions, disk full)",
    6: "Image too large for the GPU",
}

BINARY = None
WORK_ROOT = None
SESSIONS = {}


def find_binary(explicit):
    """Locate the materialize binary: --binary, then PATH, then known spots."""
    candidates = []
    if explicit:
        candidates.append(Path(explicit).expanduser())
    found = shutil.which("materialize")
    if found:
        candidates.append(Path(found))
    candidates.append(Path.home() / ".local" / "bin" / "materialize")
    candidates.append(REPO_DIR / "target" / "release" / "materialize-cli")
    for cand in candidates:
        if cand.is_file() and os.access(cand, os.X_OK):
            return cand
    return None


def binary_version(binary):
    try:
        out = subprocess.run([str(binary), "--version"], capture_output=True,
                             text=True, timeout=10)
        return out.stdout.strip() or "unknown"
    except Exception:
        return "unknown"


def run_cli(input_path, out_dir, fmt, quality):
    """Run the CLI once. Returns (exit_code, stdout, stderr, seconds)."""
    out_dir.mkdir(parents=True, exist_ok=True)
    cmd = [str(BINARY), str(input_path), "-o", str(out_dir), "-f", fmt, "-v"]
    if fmt in ("jpg", "jpeg"):
        cmd += ["-q", str(quality)]
    else:
        # The packed maps need an alpha channel, which JPEG has not got.
        cmd += ["--unity"]
    started = time.monotonic()
    proc = subprocess.run(cmd, capture_output=True, text=True, timeout=600)
    return proc.returncode, proc.stdout, proc.stderr, time.monotonic() - started


def collect_maps(out_dir, stem):
    """Match generated files by suffix rather than assuming an extension."""
    found = {}
    for name in MAPS:
        hits = sorted(out_dir.glob(f"{glob_escape(stem)}_{name}.*"))
        if hits:
            found[name] = hits[0]
    return found


def glob_escape(text):
    for ch in "[]?*":
        text = text.replace(ch, f"[{ch}]")
    return text


UNITY_README = """# {stem} - Unity material

Generated by Materialize CLI. Drop this whole folder into your project's
`Assets/` directory.

## Import settings

Get these right or the material will look wrong - the packed maps hold data,
not colour, so Unity must not apply a gamma curve to them.

| File | Texture Type | sRGB (Color Texture) |
|------|--------------|----------------------|
| `{stem}_Albedo{src_ext}` | Default | **on** |
| `{stem}_Normal{ext}` | Normal map | n/a |
| `{stem}_MaskMap{ext}` | Default | **off** |
| `{stem}_Detail{ext}` | Default | **off** |
| `{stem}_Height{ext}` | Default | **off** |

Run **Tools > Materialize > Apply Import Settings** with the folder selected to
set all of this automatically (see `Editor/`).

Prefer high-quality or uncompressed for MaskMap and Detail. Standard block
compression mixes the channels together and the packing stops being separable.

## Channel packing

`{stem}_MaskMap{ext}` follows the HDRP Mask Map layout:

| Channel | Content |
|---------|---------|
| R | Metallic |
| G | Ambient Occlusion |
| B | Detail Mask (255 everywhere - no authored mask) |
| A | Smoothness |

`{stem}_Detail{ext}` follows the HDRP Detail Map layout, where 128 is neutral:

| Channel | Content |
|---------|---------|
| R | Desaturated albedo |
| G | Normal Y |
| B | Smoothness |
| A | Normal X |

The detail map carries only the high-frequency part of the source texture, so
it layers on top of the base albedo and normal rather than repeating them.

## Assigning to an HDRP Lit material

- Base Map -> `{stem}_Albedo{src_ext}`
- Mask Map -> `{stem}_MaskMap{ext}`
- Normal Map -> `{stem}_Normal{ext}`
- Detail Map -> `{stem}_Detail{ext}` (enable Detail Inputs)
- Height Map -> `{stem}_Height{ext}` (for Displacement or Parallax Occlusion)

On URP or the Built-in pipeline there is no Mask Map input. Use the separate
metallic, smoothness and AO maps from the standard export instead.
"""

UNITY_EDITOR_SCRIPT = r"""// Applies the import settings the packed maps need.
// Tools > Materialize > Apply Import Settings, with textures or a folder selected.
using System.Collections.Generic;
using UnityEditor;
using UnityEngine;

public static class MaterializeImportSettings
{
    [MenuItem("Tools/Materialize/Apply Import Settings")]
    private static void Apply()
    {
        var guids = Selection.assetGUIDs;
        if (guids.Length == 0)
        {
            Debug.LogWarning("Materialize: select the exported folder or its textures first.");
            return;
        }

        var paths = new List<string>();
        foreach (var guid in guids)
        {
            var path = AssetDatabase.GUIDToAssetPath(guid);
            if (AssetDatabase.IsValidFolder(path))
            {
                foreach (var nested in AssetDatabase.FindAssets("t:Texture2D", new[] { path }))
                    paths.Add(AssetDatabase.GUIDToAssetPath(nested));
            }
            else
            {
                paths.Add(path);
            }
        }

        var changed = 0;
        foreach (var path in paths)
        {
            var importer = AssetImporter.GetAtPath(path) as TextureImporter;
            if (importer == null) continue;

            // Only the albedo is colour; everything else is data.
            var isNormal = path.Contains("_Normal.");
            var isAlbedo = path.Contains("_Albedo.");

            importer.textureType = isNormal
                ? TextureImporterType.NormalMap
                : TextureImporterType.Default;
            importer.sRGBTexture = isAlbedo;

            // Block compression would bleed the packed channels into each other.
            if (path.Contains("_MaskMap.") || path.Contains("_Detail."))
            {
                importer.textureCompression = TextureImporterCompression.CompressedHQ;
                importer.alphaSource = TextureImporterAlphaSource.FromInput;
                importer.alphaIsTransparency = false;
            }

            importer.SaveAndReimport();
            changed++;
        }

        Debug.Log("Materialize: updated import settings on " + changed + " texture(s).");
    }
}
"""


def build_unity_zip(session):
    """Lay the maps out as a folder a Unity project can swallow whole."""
    out_dir, stem = session["out_dir"], session["stem"]
    src = session["input"]
    found = collect_maps(out_dir, stem)
    missing = [name for _, name in UNITY_FILES if name and name not in found]
    if missing:
        raise FileNotFoundError(
            "missing " + ", ".join(missing) + " - re-run with a format that keeps alpha"
        )

    ext = found["normal"].suffix
    root = stem + "_Unity"
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.write(src, f"{root}/{stem}_Albedo{src.suffix}")
        for label, name in UNITY_FILES:
            if name:
                zf.write(found[name], f"{root}/{stem}_{label}{ext}")
        zf.writestr(f"{root}/README.md", UNITY_README.format(
            stem=stem, ext=ext, src_ext=src.suffix))
        zf.writestr(f"{root}/Editor/MaterializeImportSettings.cs",
                    UNITY_EDITOR_SCRIPT)
    return buf.getvalue(), root + ".zip"


class Handler(BaseHTTPRequestHandler):
    server_version = "MaterializeUI"

    def log_message(self, fmt, *args):
        sys.stderr.write("  %s\n" % (fmt % args))

    # -- helpers ---------------------------------------------------------
    def send_json(self, payload, status=200):
        body = json.dumps(payload).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def send_bytes(self, body, ctype, status=200, filename=None):
        self.send_response(status)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        if filename:
            self.send_header("Content-Disposition",
                             f'attachment; filename="{filename}"')
        self.end_headers()
        self.wfile.write(body)

    def session_file(self, session_id, filename):
        """Resolve a file inside a session dir, refusing path traversal."""
        session = SESSIONS.get(session_id)
        if not session:
            return None
        root = session["dir"].resolve()
        target = (root / unquote(filename)).resolve()
        if root not in target.parents or not target.is_file():
            return None
        return target

    # -- routes ----------------------------------------------------------
    def do_GET(self):
        route = urlparse(self.path)
        path = route.path

        if path in ("/", "/index.html"):
            page = (UI_DIR / "index.html").read_bytes()
            return self.send_bytes(page, "text/html; charset=utf-8")

        if path == "/api/status":
            return self.send_json({
                "binary": str(BINARY),
                "version": binary_version(BINARY),
                "maps": MAPS,
            })

        if path.startswith("/api/file/"):
            _, _, _, session_id, filename = path.split("/", 4)
            target = self.session_file(session_id, filename)
            if not target:
                return self.send_json({"error": "not found"}, 404)
            ctype = {
                ".png": "image/png", ".jpg": "image/jpeg",
                ".jpeg": "image/jpeg", ".tga": "image/x-tga",
                ".exr": "image/x-exr",
            }.get(target.suffix.lower(), "application/octet-stream")
            return self.send_bytes(target.read_bytes(), ctype)

        if path.startswith("/api/unity/"):
            session_id = path.rsplit("/", 1)[-1]
            session = SESSIONS.get(session_id)
            if not session:
                return self.send_json({"error": "unknown session"}, 404)
            try:
                blob, fname = build_unity_zip(session)
            except FileNotFoundError as exc:
                return self.send_json({"error": str(exc)}, 400)
            return self.send_bytes(blob, "application/zip", filename=fname)

        if path.startswith("/api/zip/"):
            session_id = path.rsplit("/", 1)[-1]
            session = SESSIONS.get(session_id)
            if not session:
                return self.send_json({"error": "unknown session"}, 404)
            buf = io.BytesIO()
            with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
                for path_obj in sorted(session["out_dir"].iterdir()):
                    if path_obj.is_file():
                        zf.write(path_obj, path_obj.name)
            return self.send_bytes(buf.getvalue(), "application/zip",
                                   filename=f"{session['stem']}_pbr.zip")

        return self.send_json({"error": "not found"}, 404)

    def do_POST(self):
        route = urlparse(self.path)
        if route.path != "/api/generate":
            return self.send_json({"error": "not found"}, 404)

        query = parse_qs(route.query)
        filename = query.get("name", ["texture.png"])[0]
        fmt = query.get("format", ["png"])[0].lower()
        quality = query.get("quality", ["95"])[0]
        if fmt not in ("png", "jpg", "jpeg", "tga", "exr"):
            return self.send_json({"error": f"unsupported format: {fmt}"}, 400)

        length = int(self.headers.get("Content-Length", 0))
        if not length:
            return self.send_json({"error": "empty upload"}, 400)
        data = self.rfile.read(length)

        stem = Path(filename).stem or "texture"
        suffix = Path(filename).suffix or ".png"
        session_id = uuid.uuid4().hex[:12]
        session_dir = WORK_ROOT / session_id
        (session_dir).mkdir(parents=True)
        input_path = session_dir / f"{stem}{suffix}"
        input_path.write_bytes(data)

        out_dir = session_dir / "out"
        try:
            code, stdout, stderr, secs = run_cli(input_path, out_dir, fmt, quality)
        except subprocess.TimeoutExpired:
            return self.send_json({"error": "CLI timed out after 600s"}, 500)
        except Exception as exc:
            return self.send_json({"error": f"could not run CLI: {exc}"}, 500)

        if code != 0:
            meaning = EXIT_MEANING.get(code, "Unknown error")
            return self.send_json({
                "error": f"{meaning} (exit code {code})",
                "stderr": stderr.strip(), "stdout": stdout.strip(),
            }, 500)

        # Browsers cannot display TGA/EXR, so render a PNG set purely for preview.
        preview_dir, preview_note = out_dir, None
        if fmt not in ("png", "jpg", "jpeg"):
            preview_dir = session_dir / "preview"
            try:
                pcode, _, pstderr, _ = run_cli(input_path, preview_dir, "png", 95)
                if pcode != 0:
                    preview_dir, preview_note = out_dir, pstderr.strip()
                else:
                    preview_note = f"{fmt.upper()} can't render in a browser - previewing a PNG pass."
            except Exception as exc:
                preview_dir, preview_note = out_dir, str(exc)

        saved = collect_maps(out_dir, stem)
        shown = collect_maps(preview_dir, stem)
        if not saved:
            return self.send_json({
                "error": "CLI reported success but wrote no maps",
                "stdout": stdout.strip(),
            }, 500)

        SESSIONS[session_id] = {
            "dir": session_dir, "out_dir": out_dir, "stem": stem,
            "input": input_path,
        }

        def url_for(path_obj):
            rel = path_obj.relative_to(session_dir)
            return f"/api/file/{session_id}/{rel.as_posix()}"

        return self.send_json({
            "id": session_id,
            "stem": stem,
            "format": fmt,
            "seconds": round(secs, 2),
            "original": url_for(input_path),
            "outputDir": str(out_dir),
            "note": preview_note,
            "stdout": stdout.strip(),
            "maps": [
                {
                    "name": name,
                    "preview": url_for(shown[name]) if name in shown else None,
                    "file": saved[name].name,
                    "bytes": saved[name].stat().st_size,
                }
                for name in MAPS if name in saved
            ],
        })


def main():
    global BINARY, WORK_ROOT
    parser = argparse.ArgumentParser(description="Local web UI for Materialize CLI")
    parser.add_argument("--port", type=int, default=8765)
    parser.add_argument("--binary", help="path to the materialize binary")
    parser.add_argument("--no-open", action="store_true", help="don't open a browser")
    args = parser.parse_args()

    BINARY = find_binary(args.binary)
    if not BINARY:
        print("error: could not find the 'materialize' binary.", file=sys.stderr)
        print("       install it with ./install.sh, or pass --binary PATH",
              file=sys.stderr)
        return 1

    WORK_ROOT = Path(tempfile.mkdtemp(prefix="materialize-ui-"))
    url = f"http://127.0.0.1:{args.port}/"

    print(f"Materialize UI")
    print(f"  binary   {BINARY} ({binary_version(BINARY)})")
    print(f"  scratch  {WORK_ROOT}")
    print(f"  serving  {url}")
    print("  Ctrl+C to stop\n")

    try:
        server = ThreadingHTTPServer(("127.0.0.1", args.port), Handler)
    except OSError as exc:
        if exc.errno == 48:
            print(f"error: port {args.port} is already in use.", file=sys.stderr)
            print(f"       another copy may be running - try --port {args.port + 1}",
                  file=sys.stderr)
            shutil.rmtree(WORK_ROOT, ignore_errors=True)
            return 1
        raise
    if not args.no_open:
        webbrowser.open(url)
    try:
        server.serve_forever()
    except KeyboardInterrupt:
        print("\nstopping")
    finally:
        server.server_close()
        shutil.rmtree(WORK_ROOT, ignore_errors=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
